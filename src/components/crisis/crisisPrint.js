/* ─────────────────────── KPI report ─────────────────────── */
/* targetsOverride: optional { [kpiId]: { [year]: value } } from
   crisis_settings/kpi_targets, so the printed report matches the admin-adjusted
   targets shown on-screen rather than the hard-coded catalog defaults. */
export function printKpiReport({ kpis, year, lang, locale, t, targetsOverride }) {
  const rows = KPIS.map(k => {
    const ov = targetsOverride?.[k.id]?.[year]
    const v = kpis[k.id]?.value, tgt = (ov ?? k.targets[year])
    const att = attainment(k, v, tgt), st = kpiStatusOf(att)
    const unit = k.ut === '%' ? '%' : k.ut === 'h' ? (lang === 'ar' ? ' س' : 'h') : ''
    return `<tr><td>${esc(L(k, lang))}</td><td class="num">${tgt}${unit}</td><td class="num">${v == null ? '—' : v + unit}</td><td class="num">${att == null ? '—' : Math.round(att) + '%'}</td><td>${pill(st, lang)}</td></tr>`
  }).join('')
  const body = `<table><thead><tr><th>${esc(t('Indicator', 'المؤشر'))}</th><th>${esc(t('Target', 'المستهدف'))} ${year}</th><th>${esc(t('Actual', 'الفعلي'))}</th><th>${esc(t('Attainment', 'الإنجاز'))}</th><th>${esc(t('Status', 'الحالة'))}</th></tr></thead><tbody>${rows}</tbody></table>
    <p class="muted">${esc(t('All values auto-calculated from live records. Never negative.', 'جميع القيم محسوبة تلقائياً من السجلات الحية ولا تكون سالبة.'))}</p>`
  openPrintDoc({ title: t('Crisis KPI Report', 'تقرير مؤشرات الأداء'), subtitle: `${t('Target year', 'سنة الهدف')} ${year}`, body, lang, locale })
}

/* ─────────────────────── executive summary ─────────────────────── */
export function printExecutiveSummary({ data, kpis, year, lang, locale, t }) {
  const { incidents = [], risks = [], services = [], corrective = [], exercises = [] } = data
  const active = incidents.filter(i => ['activated', 'responding', 'contained', 'recovering'].includes(i.status)).length
  const highR = risks.filter(r => ['high', 'crit'].includes(riskBand(riskScore(r.probability, r.impact)).id)).length
  const krow = (id) => { const k = findById(KPIS, id); const v = kpis[id]?.value; const unit = k.ut === '%' ? '%' : k.ut === 'h' ? (lang === 'ar' ? ' س' : 'h') : ''; return kvCell(L(k, lang), v == null ? '—' : v + unit) }
  const body = `
    <h2>${esc(t('Situation at a glance', 'الوضع باختصار'))}</h2>
    <div class="kv">
      ${kvCell(t('Active incidents', 'الحوادث النشطة'), active)}
      ${kvCell(t('Total incidents', 'إجمالي الحوادث'), incidents.length)}
      ${kvCell(t('Critical & high risks', 'مخاطر حرجة وعالية'), highR)}
      ${kvCell(t('Critical services', 'الخدمات الحيوية'), services.length)}
      ${kvCell(t('Open corrective actions', 'إجراءات تصحيحية مفتوحة'), corrective.filter(c => !['done', 'verified', 'cancelled'].includes(c.status)).length)}
      ${kvCell(t('Exercises recorded', 'التمارين المسجلة'), exercises.length)}
    </div>
    <h2>${esc(t('Readiness indicators', 'مؤشرات الجاهزية'))} · ${year}</h2>
    <div class="kv">
      ${krow('services_planned')}${krow('plans_tested')}${krow('recovery_success')}
      ${krow('avg_response')}${krow('avg_recovery')}${krow('rto_met')}
      ${krow('capa_ontime')}${krow('contacts_updated')}${krow('backup_ready')}
    </div>`
  openPrintDoc({ title: t('Executive Crisis Summary', 'الملخص التنفيذي للأزمات'), subtitle: t('Operations Department', 'إدارة العمليات'), body, lang, locale })
}

