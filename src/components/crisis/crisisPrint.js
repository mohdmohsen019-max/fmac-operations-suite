const pill = (meta, lang) => meta ? `<span class="pill" style="background:${meta.hex || TONE[meta.tone] || '#64748b'}">${esc(L(meta, lang))}</span>` : '—'
const TONE = { good: '#16a34a', info: '#2563eb', warn: '#d97706', crit: '#dc2626', neutral: '#64748b' }

const kvCell = (k, v) => `<div class="cell"><div class="k">${esc(k)}</div><div class="v">${v == null || v === '' ? '—' : esc(v)}</div></div>`

/* ─────────────────────── incident report ─────────────────────── */
export function printIncidentReport({ incident: i, decisions = [], actions = [], services = [], lang, locale, t }) {
  const svcName = (id) => { const s = services.find(x => x.id === id); return s ? (lang === 'ar' ? s.name_ar : s.name_en) : id }
  const decRows = decisions.filter(d => d.incidentId === i.id)
  const actRows = actions.filter(a => a.incidentId === i.id)
  const body = `
    <div class="kv">
      ${kvCell(t('Incident no.', 'رقم الحادث'), i.number)}
      ${kvCell(t('Kind', 'النوع'), L(findById(INCIDENT_KINDS, i.kind || 'real'), lang))}
      ${kvCell(t('Category', 'الفئة'), L(findById(INCIDENT_CATEGORIES, i.category), lang))}
      ${kvCell(t('Level', 'المستوى'), L(findById(CRISIS_LEVELS, i.level), lang))}
      ${kvCell(t('Severity', 'الخطورة'), L(findById(SEVERITIES, i.severity), lang))}
      ${kvCell(t('Status', 'الحالة'), L(findById(INCIDENT_STATUSES, i.status), lang))}
      ${kvCell(t('Location', 'الموقع'), (i.locations || []).map(l => L(findById(LOCATIONS, l), lang)).join('، '))}
      ${kvCell(t('Unit', 'الوحدة'), L(findById(ORG_UNITS, i.unit), lang))}
      ${kvCell(t('Commander', 'قائد الحدث'), L(findById(JOB_TITLES, i.commander), lang))}
      ${kvCell(t('Reported', 'وقت الإبلاغ'), fmtDateTime(i.reportedAt || i.createdAt, locale))}
      <div class="cell full"><div class="k">${esc(t('Title', 'العنوان'))}</div><div class="v">${esc(lang === 'ar' ? (i.title_ar || i.title_en) : (i.title_en || i.title_ar))}</div></div>
      <div class="cell full"><div class="k">${esc(t('Description', 'الوصف'))}</div><div class="v">${esc(i.description)}</div></div>
      <div class="cell full"><div class="k">${esc(t('Affected services', 'الخدمات المتأثرة'))}</div><div class="v">${esc((i.affectedServices || []).map(svcName).join('، '))}</div></div>
    </div>
    <h2>${esc(t('Impact assessment', 'تقييم الأثر'))}</h2>
    <div class="kv">
      ${IMPACT_DIMS.map(d => kvCell(L(d, lang), i[`impact_${d.id}`])).join('')}
    </div>
    <h2>${esc(t('Decisions', 'القرارات'))} (${decRows.length})</h2>
    ${decRows.length ? `<table><thead><tr><th>#</th><th>${esc(t('Decision', 'القرار'))}</th><th>${esc(t('Maker', 'متخذ القرار'))}</th><th>${esc(t('Time', 'الوقت'))}</th></tr></thead><tbody>
      ${decRows.map(d => `<tr><td class="num">${esc(d.number)}</td><td>${esc(d.text)}</td><td>${esc(L(findById(JOB_TITLES, d.maker), lang))}</td><td>${esc(fmtDateTime(d.createdAt, locale))}</td></tr>`).join('')}
    </tbody></table>` : `<p class="muted">${esc(t('None recorded.', 'لا يوجد.'))}</p>`}
    <h2>${esc(t('Actions', 'الإجراءات'))} (${actRows.length})</h2>
    ${actRows.length ? `<table><thead><tr><th>${esc(t('Action', 'الإجراء'))}</th><th>${esc(t('Priority', 'الأولوية'))}</th><th>${esc(t('Status', 'الحالة'))}</th><th>${esc(t('Due', 'الاستحقاق'))}</th></tr></thead><tbody>
      ${actRows.map(a => `<tr><td>${esc(lang === 'ar' ? (a.description_ar || a.description_en) : (a.description_en || a.description_ar))}</td><td>${pill(findById(PRIORITIES, a.priority), lang)}</td><td>${pill(findById(ACTION_STATUSES, a.status), lang)}</td><td>${esc(a.dueDate || '—')}</td></tr>`).join('')}
    </tbody></table>` : `<p class="muted">${esc(t('None recorded.', 'لا يوجد.'))}</p>`}
    ${i.status === 'closed' ? `<h2>${esc(t('Closure', 'الإغلاق'))}</h2><div class="kv">
      ${kvCell(t('Root cause', 'السبب الجذري'), i.rootCause)}
      ${kvCell(t('Lessons learned', 'الدروس المستفادة'), i.lessons)}
      <div class="cell full">${kvCell(t('Closure summary', 'ملخص الإغلاق'), i.closureSummary)}</div>
    </div>` : ''}`
  openPrintDoc({ title: t('Incident Report', 'تقرير حادث') + ` · ${i.number}`, subtitle: lang === 'ar' ? i.title_ar : i.title_en, body, lang, locale })
}

/* ─────────────────────── BIA report ─────────────────────── */
export function printBiaReport({ service, bia, lang, locale, t }) {
  const grid = bia?.grid || {}
  const pr = bia?.override ? { en: bia.override, ar: bia.override, tone: 'info' } : biaPriority(grid)
  const matrix = `<table class="heat"><thead><tr><th>${esc(t('Impact / Time', 'الأثر / الوقت'))}</th>${BIA_HORIZONS.map(h => `<th>${esc(L(h, lang))}</th>`).join('')}</tr></thead><tbody>
    ${IMPACT_DIMS.map(d => `<tr><th>${esc(L(d, lang))}</th>${BIA_HORIZONS.map(h => { const v = grid?.[d.id]?.[h.id] || 0; const lv = findById(BIA_LEVELS, v); return `<td style="background:${lv?.hex || '#e2e8f0'};color:#14151a">${v}</td>` }).join('')}</tr>`).join('')}
  </tbody></table>`
  const body = `
    <div class="kv">
      ${kvCell(t('Service', 'الخدمة'), lang === 'ar' ? (service.name_ar || service.name_en) : service.name_en)}
      ${kvCell(t('Unit', 'الوحدة'), L(findById(ORG_UNITS, service.unit), lang))}
      ${kvCell(t('Recovery priority', 'أولوية التعافي'), L(pr, lang))}
      ${kvCell(t('MTPD', 'أقصى انقطاع'), bia?.mtpd)}
      ${kvCell(t('RTO', 'زمن التعافي'), bia?.rto)}
      ${kvCell(t('RPO', 'نقطة التعافي'), bia?.rpo)}
      ${kvCell(t('Min. operating level', 'الحد الأدنى للتشغيل'), bia?.minLevel)}
    </div>
    <h2>${esc(t('Impact over time', 'الأثر عبر الزمن'))}</h2>
    ${matrix}
    <p class="muted">${esc(t('0 = none · 4 = severe', '0 = لا يوجد · 4 = حرج'))}</p>
    <h2>${esc(t('Continuity', 'الاستمرارية'))}</h2>
    <div class="kv">
      <div class="cell full">${kvCell(t('Dependencies', 'الاعتماديات'), bia?.dependencies)}</div>
      <div class="cell full">${kvCell(t('Resources required', 'الموارد المطلوبة'), bia?.resources)}</div>
      <div class="cell full">${kvCell(t('Recovery strategy', 'استراتيجية التعافي'), bia?.recoveryStrategy)}</div>
    </div>`
  openPrintDoc({ title: t('Business Impact Analysis', 'تحليل أثر الأعمال'), subtitle: lang === 'ar' ? service.name_ar : service.name_en, body, lang, locale })
}

/* ─────────────────────── risk register ─────────────────────── */
export function printRiskRegister({ risks, lang, locale, t }) {
  const rows = risks.map(r => {
    const s = riskScore(r.probability, r.impact), b = riskBand(s)
    return `<tr><td>${esc(lang === 'ar' ? (r.title_ar || r.title_en) : r.title_en)}</td><td>${esc(L(findById(INCIDENT_CATEGORIES, r.category), lang))}</td><td class="num">${r.probability || '—'}</td><td class="num">${r.impact || '—'}</td><td class="num">${s || '—'}</td><td>${pill(b, lang)}</td><td>${esc(L(findById(JOB_TITLES, r.owner), lang))}</td></tr>`
  }).join('')
  const body = `<table><thead><tr><th>${esc(t('Risk', 'المخاطرة'))}</th><th>${esc(t('Category', 'الفئة'))}</th><th>P</th><th>I</th><th>${esc(t('Score', 'الدرجة'))}</th><th>${esc(t('Level', 'المستوى'))}</th><th>${esc(t('Owner', 'المالك'))}</th></tr></thead><tbody>${rows || `<tr><td colspan="7" class="muted">${esc(t('No risks.', 'لا مخاطر.'))}</td></tr>`}</tbody></table>`
  openPrintDoc({ title: t('Critical Risk Register', 'سجل المخاطر الحرجة'), subtitle: `${risks.length} ${t('risks', 'مخاطرة')}`, body, lang, locale })
}

